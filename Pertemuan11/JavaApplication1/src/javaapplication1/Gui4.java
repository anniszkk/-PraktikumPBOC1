    private void jSaveDataMapActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jSaveDataMapActionPerformed
        // TODO add your handling code here:
        itemMap.clear();
        for (int i = 0; i < dlm.getSize(); i++) {
            itemMap.put(i, dlm.getElementAt(i)); 
        }
        updateJumDataTersimpanMap();
    }//GEN-LAST:event_jSaveDataMapActionPerformed

