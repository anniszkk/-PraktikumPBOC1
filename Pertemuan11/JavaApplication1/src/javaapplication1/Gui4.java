    private void jSaveDataSetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jSaveDataSetActionPerformed
        // TODO add your handling code here:
        itemSet.clear();
        for (int i = 0; i < dlm.getSize(); i++) {
            itemSet.add(dlm.getElementAt(i));
        }
        updateJumDataTersimpanSet();
    }//GEN-LAST:event_jSaveDataSetActionPerformed

